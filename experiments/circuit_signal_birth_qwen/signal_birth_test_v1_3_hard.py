# -*- coding: utf-8 -*-
"""
Signal Birth controlled hard test v1.3
version: v1.3.0-hard-compose-residual-aware-sequential

Harder than v1.1:
- No direct BIRTH_* candidate is provided.
- Hidden residual is generated by formulas composed from primitive atoms.
- Miner must compose formulas from atoms + unary ops + multiply.
- Includes train-only spurious candidates that can win train but must fail heldout.
- Includes retain split where missing context gate hurts retain.
- Accept rule: residual-aware train/heldout gain + strict retain safe + generalization + non-duplicate.
"""

import argparse
import math
import time
from dataclasses import dataclass
from typing import Dict, List, Tuple

import torch
import torch.nn.functional as F

VERSION = "v1.3.0-hard-compose-residual-aware-strict-refit"


@dataclass
class Expr:
    name: str
    train: torch.Tensor
    held: torch.Tensor
    retain: torch.Tensor
    depth: int
    origin: str = "compose"


@dataclass
class EvalRow:
    name: str
    train_gain: float
    held_gain: float
    retain_delta: float
    gen_ratio: float
    dup_corr: float
    true_corr: float
    ok: bool
    origin: str


@dataclass
class SplitPack:
    atoms: Dict[str, torch.Tensor]
    base: torch.Tensor
    y: torch.Tensor
    hidden: List[torch.Tensor]
    hidden_names: List[str]


def make_gen(seed: int, device: torch.device) -> torch.Generator:
    # CUDA generators are supported by torch.randn(shape, generator=gen, device=device)
    gen = torch.Generator(device=device.type)
    gen.manual_seed(seed)
    return gen


def randn(shape, gen, device, dtype=torch.float32):
    return torch.randn(shape, generator=gen, device=device, dtype=dtype)


def zscore_by_train(x_train, x_held, x_retain, eps=1e-6):
    mu = x_train.mean()
    sd = x_train.std(unbiased=False).clamp_min(eps)
    return (x_train - mu) / sd, (x_held - mu) / sd, (x_retain - mu) / sd



def scale_by_train(x_train, x_held, x_retain, eps=1e-6):
    # Preserve closed gates: if held/retain value is 0, it remains 0.
    # This is important for edit-only signals; zscore would turn closed gate into negative offset.
    sd = x_train.std(unbiased=False).clamp_min(eps)
    return x_train / sd, x_held / sd, x_retain / sd

def zscore_single(x, ref=None, eps=1e-6):
    if ref is None:
        ref = x
    return (x - ref.mean()) / ref.std(unbiased=False).clamp_min(eps)


def mse_resid(resid: torch.Tensor) -> float:
    return float((resid * resid).mean().detach().cpu())


def ridge_fit(X: torch.Tensor, Y: torch.Tensor, ridge: float = 1e-5) -> torch.Tensor:
    # X [N,P], Y [N,O] => coef [P,O]
    P = X.shape[1]
    eye = torch.eye(P, device=X.device, dtype=X.dtype)
    A = X.T @ X + ridge * eye
    B = X.T @ Y
    return torch.linalg.solve(A, B)


def make_split(n: int, dim: int, out_dim: int, seed: int, device: torch.device, split: str, hard_retain: bool):
    gen = make_gen(seed, device)

    act = randn((n, dim), gen, device)
    blame = randn((n, dim), gen, device)
    noise = 0.10 * randn((n, dim), gen, device)

    # Context is available as a raw primitive, but the true gate pos(ctx) is not handed directly.
    if split in ("train", "held"):
        ctx = 1.0 + 0.35 * randn((n,), gen, device)
    else:
        # hard retain: close to boundary, not simply all-zero, so missing ctx gate can hurt.
        center = -3.0 if hard_retain else -2.2
        ctx = center + 0.25 * randn((n,), gen, device)

    # Fixed deterministic probes by seed family, not learnable.
    # Same probe basis across train/heldout/retain for a given test; otherwise heldout becomes a different task.
    g_probe = make_gen(7777, device)
    P = F.normalize(randn((8, dim), g_probe, device), dim=1)

    act_p = act @ P.T
    blame_p = blame @ P.T

    # mask/probe focus is a primitive derived from act/blame, not hidden label.
    mask_raw = 0.65 * act_p[:, 4] - 0.35 * blame_p[:, 5] + 0.10 * noise[:, 0]
    probe_raw = 0.50 * act_p[:, 6] + 0.40 * blame_p[:, 7] + 0.10 * noise[:, 1]

    atoms = {
        "act_p0": act_p[:, 0],
        "act_p1": act_p[:, 1],
        "act_p2": act_p[:, 2],
        "act_p3": act_p[:, 3],
        "blame_p0": blame_p[:, 0],
        "blame_p1": blame_p[:, 1],
        "blame_p2": blame_p[:, 2],
        "blame_p3": blame_p[:, 3],
        "mask_raw": mask_raw,
        "probe_raw": probe_raw,
        "ctx_raw": ctx,
        "ctx_gate": F.relu(ctx),
        "mask_gate": F.relu(mask_raw),
        "act_mean": act.mean(dim=1),
        "blame_mean": blame.mean(dim=1),
    }

    # Base support/contradiction/novelty: deliberately cannot express hidden residual fully.
    support = torch.tanh(0.75 * act_p[:, 1] + 0.25 * blame_p[:, 2])
    contradiction = torch.tanh(act_p[:, 3] * blame_p[:, 0])
    novelty = torch.tanh((act_p[:, 2] - blame_p[:, 1]).abs() - 0.6)
    base = torch.stack([support, contradiction, novelty], dim=1)

    # Hidden formulas. They are NOT inserted into candidate list directly.
    # Candidate composer must rediscover approximations from atoms using square/center/pos/tanh/abs/mul.
    ctx_gate = F.relu(ctx)
    h1_raw = ((act_p[:, 0] ** 2) - (act_p[:, 0] ** 2).mean()) * torch.tanh(blame_p[:, 1]) * F.relu(mask_raw) * ctx_gate
    h2_raw = F.relu(act_p[:, 2] - 0.25) * blame_p[:, 3].abs() * torch.tanh(probe_raw) * ctx_gate

    # Return raw hidden. build_dataset scales all splits by train stats.
    return atoms, base, [h1_raw, h2_raw], [
        "TRUE_compose:center(square(act_p0))*tanh(blame_p1)*pos(mask_raw)*pos(ctx_raw)",
        "TRUE_compose:pos(act_p2-0.25)*abs(blame_p3)*tanh(probe_raw)*pos(ctx_raw)",
    ]


def build_dataset(args, seed: int, device: torch.device):
    # Data split seeds are separated but generated by same process.
    tr_atoms, tr_base, tr_hidden, hidden_names = make_split(args.n_train, args.dim, args.out_dim, seed * 100 + 1, device, "train", args.hard_retain)
    he_atoms, he_base, he_hidden, _ = make_split(args.n_heldout, args.dim, args.out_dim, seed * 100 + 2, device, "held", args.hard_retain)
    re_atoms, re_base, re_hidden, _ = make_split(args.n_retain, args.dim, args.out_dim, seed * 100 + 3, device, "retain", args.hard_retain)

    # Scale true hidden signals by train std without centering, preserving closed retain gates.
    for hi in range(2):
        tr_h, he_h, re_h = scale_by_train(tr_hidden[hi], he_hidden[hi], re_hidden[hi])
        tr_hidden[hi], he_hidden[hi], re_hidden[hi] = tr_h, he_h, re_h

    gen = make_gen(seed * 100 + 99, device)
    base_coef = 0.8 * randn((3, args.out_dim), gen, device)
    hidden_coef_1 = args.hidden_strength * F.normalize(randn((args.out_dim,), gen, device), dim=0)
    hidden_coef_2 = args.hidden2_strength * F.normalize(randn((args.out_dim,), gen, device), dim=0)

    def y_from(base, hidden, is_retain=False):
        y = base @ base_coef
        # Retain target does not contain the edit-only hidden residual. A candidate lacking ctx gate will hurt retain.
        if not is_retain:
            y = y + hidden[0].unsqueeze(1) * hidden_coef_1.unsqueeze(0)
            if args.hidden_signals >= 2:
                y = y + hidden[1].unsqueeze(1) * hidden_coef_2.unsqueeze(0)
        return y

    y_train = y_from(tr_base, tr_hidden, False)
    y_held = y_from(he_base, he_hidden, False)
    y_retain = y_from(re_base, re_hidden, True)

    if args.target_noise > 0:
        y_train = y_train + args.target_noise * randn(y_train.shape, gen, device)
        y_held = y_held + args.target_noise * randn(y_held.shape, gen, device)
        y_retain = y_retain + args.target_noise * randn(y_retain.shape, gen, device)

    packs = {
        "train": SplitPack(tr_atoms, tr_base, y_train, tr_hidden, hidden_names),
        "held": SplitPack(he_atoms, he_base, y_held, he_hidden, hidden_names),
        "retain": SplitPack(re_atoms, re_base, y_retain, re_hidden, hidden_names),
    }
    return packs


def init_exprs_from_atoms(packs: Dict[str, SplitPack], args) -> List[Expr]:
    exprs = []
    keys = list(packs["train"].atoms.keys())
    for k in keys:
        if "gate" in k:
            tr, he, re = scale_by_train(packs["train"].atoms[k], packs["held"].atoms[k], packs["retain"].atoms[k])
        else:
            tr, he, re = zscore_by_train(packs["train"].atoms[k], packs["held"].atoms[k], packs["retain"].atoms[k])
        exprs.append(Expr(k, tr, he, re, depth=0, origin="atom"))
    return exprs


def unary_expr(e: Expr, op: str) -> Expr:
    if op == "square":
        tr, he, re = e.train ** 2, e.held ** 2, e.retain ** 2
        name = f"square({e.name})"
    elif op == "abs":
        tr, he, re = e.train.abs(), e.held.abs(), e.retain.abs()
        name = f"abs({e.name})"
    elif op == "pos":
        tr, he, re = F.relu(e.train), F.relu(e.held), F.relu(e.retain)
        name = f"pos({e.name})"
    elif op == "negpos":
        tr, he, re = F.relu(-e.train), F.relu(-e.held), F.relu(-e.retain)
        name = f"pos(-{e.name})"
    elif op == "tanh":
        tr, he, re = torch.tanh(e.train), torch.tanh(e.held), torch.tanh(e.retain)
        name = f"tanh({e.name})"
    elif op == "center_square":
        tr0, he0, re0 = e.train ** 2, e.held ** 2, e.retain ** 2
        mu = tr0.mean()
        tr, he, re = tr0 - mu, he0 - mu, re0 - mu
        name = f"center(square({e.name}))"
    else:
        raise ValueError(op)
    if "gate" in e.name:
        tr, he, re = scale_by_train(tr, he, re)
    else:
        tr, he, re = zscore_by_train(tr, he, re)
    return Expr(name, tr, he, re, e.depth + 1, origin="unary")


def mul_expr(a: Expr, b: Expr) -> Expr:
    tr, he, re = a.train * b.train, a.held * b.held, a.retain * b.retain
    # scale-only keeps gated edit signals near zero on retain.
    tr, he, re = scale_by_train(tr, he, re)
    return Expr(f"mul({a.name},{b.name})", tr, he, re, max(a.depth, b.depth) + 1, origin="compose")


def corr_abs(a: torch.Tensor, b: torch.Tensor, eps=1e-8) -> float:
    a = a - a.mean()
    b = b - b.mean()
    c = (a * b).mean() / (a.std(unbiased=False).clamp_min(eps) * b.std(unbiased=False).clamp_min(eps))
    return float(c.abs().detach().cpu())


def residual_energy_score(e: Expr, resid_train: torch.Tensor) -> float:
    # Good cheap score for beam filtering: multi-output residual explained energy.
    c = e.train
    denom = (c * c).sum().clamp_min(1e-8)
    num = c @ resid_train
    gain = (num * num).sum() / denom / resid_train.numel()
    return float(gain.detach().cpu())


def dedup_by_name(exprs: List[Expr]) -> List[Expr]:
    out = []
    seen = set()
    for e in exprs:
        if e.name not in seen and torch.isfinite(e.train).all() and e.train.std(unbiased=False) > 1e-5:
            seen.add(e.name)
            out.append(e)
    return out


def build_composed_candidates(packs: Dict[str, SplitPack], resid_train: torch.Tensor, args, seed: int, device: torch.device) -> List[Expr]:
    atoms = init_exprs_from_atoms(packs, args)
    unary_ops = ["square", "abs", "pos", "negpos", "tanh", "center_square"]
    unary = []
    for e in atoms:
        for op in unary_ops:
            unary.append(unary_expr(e, op))
    pool0 = dedup_by_name(atoms + unary)

    # No direct true candidate is added. Only formulas composed from primitive atoms.
    # Beam is based on residual explained energy, not hidden label.
    scored0 = sorted(pool0, key=lambda e: residual_energy_score(e, resid_train), reverse=True)
    base_pool = scored0[: args.beam_atoms]

    pair = []
    for i in range(len(base_pool)):
        for j in range(i, len(base_pool)):
            pair.append(mul_expr(base_pool[i], base_pool[j]))
    pair = dedup_by_name(pair)
    pair = sorted(pair, key=lambda e: residual_energy_score(e, resid_train), reverse=True)[: args.beam_pairs]

    triple = []
    for a in pair[: args.triple_from_pairs]:
        for b in base_pool[: args.triple_atoms]:
            # avoid insane duplicate self-products too often, but allow useful products
            triple.append(mul_expr(a, b))
    triple = dedup_by_name(triple)
    triple = sorted(triple, key=lambda e: residual_energy_score(e, resid_train), reverse=True)[: args.beam_triples]

    quad = []
    if args.max_depth >= 4:
        for a in triple[: args.quad_from_triples]:
            for b in base_pool[: args.quad_atoms]:
                quad.append(mul_expr(a, b))
        quad = dedup_by_name(quad)
        quad = sorted(quad, key=lambda e: residual_energy_score(e, resid_train), reverse=True)[: args.beam_quads]

    grammar = []
    if args.grammar_products:
        # Generic category grammar, not direct hidden insertion:
        # compose candidate signals from activation terms, blame terms, gates, and probe terms.
        # This fixes pure beam pruning failure on multiplicative signals where intermediate factors
        # have low individual residual correlation.
        def take_group(substrs, limit):
            xs = []
            for e in pool0:
                if any(ss in e.name for ss in substrs):
                    xs.append(e)
            xs = dedup_by_name(xs)
            xs = sorted(xs, key=lambda e: residual_energy_score(e, resid_train), reverse=True)
            return xs[:limit]

        act_terms = take_group(["act_p"], args.grammar_act_terms)
        blame_terms = take_group(["blame_p"], args.grammar_blame_terms)
        mask_terms = take_group(["mask_gate", "mask_raw"], args.grammar_gate_terms)
        ctx_terms = take_group(["ctx_gate", "ctx_raw"], args.grammar_gate_terms)
        probe_terms = take_group(["probe_raw"], args.grammar_probe_terms)

        # act * blame * mask * ctx family
        for a in act_terms:
            for b in blame_terms:
                ab = mul_expr(a, b)
                for m in mask_terms:
                    abm = mul_expr(ab, m)
                    for c in ctx_terms:
                        grammar.append(mul_expr(abm, c))

        # act * blame * probe * ctx family
        for a in act_terms:
            for b in blame_terms:
                ab = mul_expr(a, b)
                for pr in probe_terms:
                    abp = mul_expr(ab, pr)
                    for c in ctx_terms:
                        grammar.append(mul_expr(abp, c))

        grammar = dedup_by_name(grammar)
        grammar = sorted(grammar, key=lambda e: residual_energy_score(e, resid_train), reverse=True)[: args.beam_grammar]

    # Spurious train-only traps. They are allowed into candidate set and should be rejected by heldout/generalization.
    spur = []
    if args.spurious_count > 0:
        gen = make_gen(seed * 1000 + 555, device)
        # Build a train vector from residual projection; held/retain are unrelated random vectors.
        direction = F.normalize(randn((resid_train.shape[1],), gen, device), dim=0)
        leak_train = resid_train @ direction
        leak_train = zscore_single(leak_train)
        for si in range(args.spurious_count):
            tr = leak_train + 0.05 * randn(leak_train.shape, gen, device)
            he = randn((packs["held"].y.shape[0],), gen, device)
            re = randn((packs["retain"].y.shape[0],), gen, device)
            tr, he, re = zscore_by_train(tr, he, re)
            spur.append(Expr(f"SPURIOUS_train_only_leak_{si:02d}", tr, he, re, 99, origin="spurious"))

    all_candidates = dedup_by_name(pool0 + pair + triple + quad + grammar + spur)
    # Keep bounded but do not remove spurious traps.
    non_spur = [e for e in all_candidates if e.origin != "spurious"]
    non_spur = sorted(non_spur, key=lambda e: residual_energy_score(e, resid_train), reverse=True)[: args.max_candidates]
    return non_spur + spur


def eval_candidates(cands: List[Expr], resid_tr: torch.Tensor, resid_he: torch.Tensor, resid_re: torch.Tensor,
                    base_exprs: List[Expr], true_hidden: List[Tuple[torch.Tensor, torch.Tensor, torch.Tensor]], args) -> List[EvalRow]:
    device = resid_tr.device
    O = resid_tr.shape[1]
    before_tr_sse = (resid_tr * resid_tr).sum()
    before_he_sse = (resid_he * resid_he).sum()
    before_re_sse = (resid_re * resid_re).sum()
    rows: List[EvalRow] = []

    # duplicate reference vectors: initial bank/base signals + accepted candidates are added outside by caller via base_exprs.
    ref_tr = [e.train for e in base_exprs]

    for start in range(0, len(cands), args.eval_chunk):
        chunk = cands[start:start + args.eval_chunk]
        Ctr = torch.stack([e.train for e in chunk], dim=0)  # [C,N]
        Che = torch.stack([e.held for e in chunk], dim=0)
        Cre = torch.stack([e.retain for e in chunk], dim=0)

        denom_tr = (Ctr * Ctr).sum(dim=1).clamp_min(1e-8)  # [C]
        num_tr = Ctr @ resid_tr  # [C,O]
        W = num_tr / denom_tr.unsqueeze(1)  # [C,O]

        # SSE after with train-fitted W.
        gain_tr_abs = ((num_tr * num_tr).sum(dim=1) / denom_tr) / resid_tr.numel()

        num_he = Che @ resid_he
        denom_he = (Che * Che).sum(dim=1)
        after_he_sse = before_he_sse - 2.0 * (W * num_he).sum(dim=1) + (W * W).sum(dim=1) * denom_he
        gain_he_abs = (before_he_sse - after_he_sse) / resid_he.numel()

        num_re = Cre @ resid_re
        denom_re = (Cre * Cre).sum(dim=1)
        after_re_sse = before_re_sse - 2.0 * (W * num_re).sum(dim=1) + (W * W).sum(dim=1) * denom_re
        delta_re = (after_re_sse - before_re_sse) / resid_re.numel()

        for idx, e in enumerate(chunk):
            tg = float(gain_tr_abs[idx].detach().cpu())
            hg = float(gain_he_abs[idx].detach().cpu())
            rd = float(delta_re[idx].detach().cpu())
            gr = hg / max(tg, 1e-12)

            dup = 0.0
            for r in ref_tr:
                dup = max(dup, corr_abs(e.train, r))

            tc = 0.0
            for htr, hhe, hre in true_hidden:
                # report heldout correlation too, but train is enough for sorting truth recovery.
                tc = max(tc, corr_abs(e.held, hhe))

            cur_train_mse = float((before_tr_sse / resid_tr.numel()).detach().cpu())
            cur_held_mse = float((before_he_sse / resid_he.numel()).detach().cpu())
            cur_retain_mse = float((before_re_sse / resid_re.numel()).detach().cpu())

            min_train_gain = max(args.min_train_gain, args.min_train_gain_frac * cur_train_mse)
            min_held_gain = max(args.min_held_gain, args.min_held_gain_frac * cur_held_mse)
            max_retain_delta = min(
                args.max_retain_delta,
                max(args.max_retain_delta_floor, args.max_retain_delta_frac * max(cur_retain_mse, 1e-12)),
            )
            positive_retain = max(rd, 0.0)

            ok = (
                tg >= min_train_gain and
                hg >= min_held_gain and
                gr >= args.min_generalization_ratio and
                rd <= max_retain_delta and
                hg >= args.retain_penalty_ratio * positive_retain and
                dup <= args.max_dup_corr
            )
            rows.append(EvalRow(e.name, tg, hg, rd, gr, dup, tc, ok, e.origin))

    rows.sort(key=lambda r: (r.ok, r.held_gain, r.train_gain), reverse=True)
    return rows


def add_candidate_to_residual(chosen: Expr, resid_tr, resid_he, resid_re):
    denom = (chosen.train * chosen.train).sum().clamp_min(1e-8)
    W = (chosen.train @ resid_tr) / denom  # [O]
    resid_tr2 = resid_tr - chosen.train.unsqueeze(1) * W.unsqueeze(0)
    resid_he2 = resid_he - chosen.held.unsqueeze(1) * W.unsqueeze(0)
    resid_re2 = resid_re - chosen.retain.unsqueeze(1) * W.unsqueeze(0)
    return resid_tr2, resid_he2, resid_re2, W


def run_one(seed: int, args, device: torch.device):
    packs = build_dataset(args, seed, device)

    # Fit only initial bank: support / contradiction / novelty.
    coef0 = ridge_fit(packs["train"].base, packs["train"].y, args.ridge)
    pred_tr0 = packs["train"].base @ coef0
    pred_he0 = packs["held"].base @ coef0
    pred_re0 = packs["retain"].base @ coef0

    resid_tr = packs["train"].y - pred_tr0
    resid_he = packs["held"].y - pred_he0
    resid_re = packs["retain"].y - pred_re0

    before = (mse_resid(resid_tr), mse_resid(resid_he), mse_resid(resid_re))

    # Initial bank reference expressions for duplicate rejection.
    base_exprs = []
    for bi, name in enumerate(["support", "contradiction", "novelty"]):
        tr, he, re = zscore_by_train(packs["train"].base[:, bi], packs["held"].base[:, bi], packs["retain"].base[:, bi])
        base_exprs.append(Expr(name, tr, he, re, 0, origin="initial_bank"))

    true_hidden = []
    for hi in range(args.hidden_signals):
        # zscore true hidden by train stats for correlation reporting.
        tr, he, re = zscore_by_train(packs["train"].hidden[hi], packs["held"].hidden[hi], packs["retain"].hidden[hi])
        true_hidden.append((tr, he, re))

    accepted: List[Tuple[Expr, EvalRow]] = []
    top_rows_last = []
    all_candidates_count = 0
    t0 = time.time()

    for birth_step in range(args.max_births):
        # Sequential residual refit: stop once heldout residual is already small.
        # This prevents weak late births from being accepted just because they shave tiny noise.
        if mse_resid(resid_he) <= args.stop_held_mse:
            break
        cands = build_composed_candidates(packs, resid_tr, args, seed + 100 * birth_step, device)
        all_candidates_count += len(cands)
        rows = eval_candidates(cands, resid_tr, resid_he, resid_re, base_exprs, true_hidden, args)
        top_rows_last = rows[: args.print_top]
        chosen_row = None
        chosen_expr = None
        name_to_expr = {e.name: e for e in cands}
        for r in rows:
            if r.ok:
                chosen_row = r
                chosen_expr = name_to_expr[r.name]
                break
        if chosen_expr is None:
            break
        accepted.append((chosen_expr, chosen_row))
        base_exprs.append(chosen_expr)
        resid_tr, resid_he, resid_re, _ = add_candidate_to_residual(chosen_expr, resid_tr, resid_he, resid_re)

    after = (mse_resid(resid_tr), mse_resid(resid_he), mse_resid(resid_re))

    # Count recovery: accepted signal correlates with any true hidden formula on heldout.
    recovered = 0
    for _, row in accepted:
        if row.true_corr >= args.true_corr_threshold:
            recovered += 1

    return {
        "seed": seed,
        "before": before,
        "after": after,
        "accepted": [(e.name, r) for e, r in accepted],
        "recovered": recovered,
        "top_rows": top_rows_last,
        "candidate_count": all_candidates_count,
        "elapsed": time.time() - t0,
    }


def fmt_name(name: str, width=88):
    if len(name) <= width:
        return name.ljust(width)
    return (name[:width - 3] + "...").ljust(width)


